create table if not exists public.musteri_tahsilat_ozet (
    musteri_kodu         text primary key references public.musteriler (musteri_kodu) on delete cascade,
    son_tahsilat_tarihi  date,
    tahsilat_7g          numeric(16,2) not null default 0,
    tahsilat_30g         numeric(16,2) not null default 0,
    tahsilat_ytd         numeric(16,2) not null default 0,
    odenmemis_tutar      numeric(16,2) not null default 0,
    odenmemis_adet       integer not null default 0,
    satir_sayisi         integer not null default 0,
    guncellendi          timestamptz not null default now()
);

alter table public.musteri_tahsilat_ozet enable row level security;

do $$ begin
  create policy "musteri_tahsilat_ozet_select_public"
    on public.musteri_tahsilat_ozet
    for select
    to anon, authenticated
    using (true);
exception when duplicate_object then null;
end $$;

grant select on public.musteri_tahsilat_ozet to anon, authenticated, service_role;

create or replace function public.replace_musteri_tahsilat_ozet(p_rows jsonb)
returns integer
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  n integer := 0;
begin
  if not pg_try_advisory_xact_lock(hashtext('replace_musteri_tahsilat_ozet')) then
    raise notice 'replace_musteri_tahsilat_ozet: already running, skipping';
    return 0;
  end if;

  if p_rows is not null and jsonb_typeof(p_rows) is distinct from 'array' then
    raise exception 'replace_musteri_tahsilat_ozet: p_rows must be a JSON array';
  end if;

  delete from public.musteri_tahsilat_ozet
  where musteri_kodu is not null;

  if p_rows is null or jsonb_array_length(p_rows) = 0 then
    return 0;
  end if;

  insert into public.musteri_tahsilat_ozet (
    musteri_kodu,
    son_tahsilat_tarihi,
    tahsilat_7g,
    tahsilat_30g,
    tahsilat_ytd,
    odenmemis_tutar,
    odenmemis_adet,
    satir_sayisi,
    guncellendi
  )
  select
    r.musteri_kodu,
    r.son_tahsilat_tarihi,
    coalesce(r.tahsilat_7g, 0),
    coalesce(r.tahsilat_30g, 0),
    coalesce(r.tahsilat_ytd, 0),
    coalesce(r.odenmemis_tutar, 0),
    coalesce(r.odenmemis_adet, 0),
    coalesce(r.satir_sayisi, 0),
    now()
  from jsonb_to_recordset(p_rows) as r(
    musteri_kodu text,
    son_tahsilat_tarihi date,
    tahsilat_7g numeric,
    tahsilat_30g numeric,
    tahsilat_ytd numeric,
    odenmemis_tutar numeric,
    odenmemis_adet integer,
    satir_sayisi integer
  )
  where r.musteri_kodu is not null and btrim(r.musteri_kodu) <> '';

  get diagnostics n = row_count;
  return n;
end;
$function$;

revoke all on function public.replace_musteri_tahsilat_ozet(jsonb) from public, anon, authenticated;
grant execute on function public.replace_musteri_tahsilat_ozet(jsonb) to service_role;

