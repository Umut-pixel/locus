  on public.panorama_tahsilat_raporu (musteri_kod);

alter table public.panorama_tahsilat_raporu enable row level security;

do $$ begin
  create policy "panorama_tahsilat_raporu_select_public"
    on public.panorama_tahsilat_raporu
    for select
    to anon, authenticated
    using (true);
exception when duplicate_object then null;
end $$;

grant select, insert, update, delete on public.panorama_tahsilat_raporu
  to anon, authenticated, service_role;

grant usage, select on sequence public.panorama_tahsilat_raporu_id_seq
  to anon, authenticated, service_role;

create view public.v_panorama_tahsilat_raporu_guncel
with (security_invoker = true) as
select *
  from public.panorama_tahsilat_raporu m
 where m.sync_id = (
   select r.id
     from public.panorama_sync_runs r
    where r.durum = 'completed'
      and r.report_id = 5230
    order by r.cekildi_at desc
    limit 1
 );

grant select on public.v_panorama_tahsilat_raporu_guncel to anon, authenticated, service_role;

