    satis_temsilcisi       text,
    tc_kimlik_no           text,
    vergi_no               text,
    tahsilat_tur           text,
    dist                   text,
    musteri_kod            text,
    musteri_unvan          text,
    islem_tarihi           text,
    islem_tip              text,
    ba                     text,
    giris_tipi             text,
    belgekod               text,
    banka                  text,
    belge_no               text,
    makbuz_no              text,
    tahsilat_tipi          text,
    rut_grup_ad            text,
    tahsilat_iptal_neden   text,
    musteri_grup_kodu      text,
    musteri_ek_grup_kod    text,
    musteri_grup_ad        text,
    musteri_ek_grup_ad     text,
    esas_borclu            text,
